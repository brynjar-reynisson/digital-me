-- Gradual nomic-embed-text to bge-m3 migration schema.
-- MIGRATED_AT is an ISO-8601 instant, NULL until the file has been copied into MCP_EMBEDDING_V2.
ALTER TABLE MCP_EMBEDDING ADD COLUMN MIGRATED_AT TEXT;
CREATE INDEX mcp_embedding_unmigrated_idx ON MCP_EMBEDDING (FILE_PATH) WHERE MIGRATED_AT IS NULL;

CREATE TABLE MCP_EMBEDDING_V2 (
    FILE_PATH   TEXT NOT NULL,
    CHUNK_INDEX INTEGER NOT NULL DEFAULT 0,
    SOURCE_URL  TEXT NOT NULL,
    CHUNK_TEXT  TEXT NOT NULL,
    EMBEDDING   extensions.VECTOR(1024) NOT NULL,
    MODEL       TEXT NOT NULL,
    INDEXED_AT  TEXT NOT NULL,
    PRIMARY KEY (FILE_PATH, CHUNK_INDEX)
);
CREATE INDEX mcp_embedding_v2_hnsw_idx ON MCP_EMBEDDING_V2
    USING hnsw (EMBEDDING extensions.vector_cosine_ops);
CREATE INDEX mcp_embedding_v2_source_idx ON MCP_EMBEDDING_V2 (SOURCE_URL);

INSERT INTO APPLICATION_METADATA (KEY, VALUE) VALUES ('database.version', '3')
ON CONFLICT (KEY) DO UPDATE SET VALUE = '3';
